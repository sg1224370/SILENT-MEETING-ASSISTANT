COMMAND_LABELS = [
    '0: YES 👍',
    '1: NO 👎',
    '2: I WANT TO SPEAK 🖐️',
    '3: HELLO 👋',
    '4: STOP ✊',
    '5: I NEED HELP ☝️',
    '6: THANK YOU 🤟',
    '7: WAIT ✌️',
]


def resource_path(relative_path):
    base_path = Path(getattr(sys, '_MEIPASS', Path(__file__).resolve().parent))
    return str(base_path / relative_path)


def get_args():
    parser = argparse.ArgumentParser()

    parser.add_argument("--device", type=int, default=0)
    parser.add_argument("--width", help='cap width', type=int, default=960)
    parser.add_argument("--height", help='cap height', type=int, default=540)

    parser.add_argument('--use_static_image_mode', action='store_true')
    parser.add_argument("--min_detection_confidence",
                        help='min_detection_confidence',
                        type=float,
                        default=0.7)
    parser.add_argument("--min_tracking_confidence",
                        help='min_tracking_confidence',
                        type=float,
                        default=0.5)
    parser.add_argument('--stable-frames', type=int, default=8,
                        help='consecutive frames required to fire a command')
    parser.add_argument('--cooldown', type=float, default=2.0,
                        help='seconds before another command may fire')
    parser.add_argument('--voice', action='store_true',
                        help='speak fired commands with pyttsx3 when available')

    args = parser.parse_args()

    return args


def main():
    # 引数解析 #################################################################
    args = get_args()

    cap_device = args.device
    cap_width = args.width
    cap_height = args.height

    use_static_image_mode = args.use_static_image_mode
    min_detection_confidence = args.min_detection_confidence
    min_tracking_confidence = args.min_tracking_confidence
    stable_frames_required = max(1, args.stable_frames)

    use_brect = True

    # カメラ準備 ###############################################################
    cap = cv.VideoCapture(cap_device)
    cap.set(cv.CAP_PROP_FRAME_WIDTH, cap_width)
    cap.set(cv.CAP_PROP_FRAME_HEIGHT, cap_height)

    # モデルロード #############################################################
    hand_options = vision.HandLandmarkerOptions(
        base_options=python.BaseOptions(
            model_asset_path=resource_path('model/hand_landmarker.task')),
        running_mode=(vision.RunningMode.IMAGE
                      if use_static_image_mode else vision.RunningMode.VIDEO),
        num_hands=1,
        min_hand_detection_confidence=min_detection_confidence,
        min_tracking_confidence=min_tracking_confidence,
    )
    hands = vision.HandLandmarker.create_from_options(hand_options)

    keypoint_classifier = KeyPointClassifier(
        model_path=resource_path('model/keypoint_classifier/keypoint_classifier.tflite'))
    point_history_classifier = PointHistoryClassifier(
        model_path=resource_path('model/point_history_classifier/point_history_classifier.tflite'))

    # ラベル読み込み ###########################################################
    with open(resource_path('model/keypoint_classifier/keypoint_classifier_label.csv'),
              encoding='utf-8-sig') as f:
        keypoint_classifier_labels = csv.reader(f)
        keypoint_classifier_labels = [
            row[0] for row in keypoint_classifier_labels
        ]
    with open(resource_path('model/point_history_classifier/point_history_classifier_label.csv'),
              encoding='utf-8-sig') as f:
        point_history_classifier_labels = csv.reader(f)
        point_history_classifier_labels = [
            row[0] for row in point_history_classifier_labels
        ]
    # FPS計測モジュール ########################################################
    cvFpsCalc = CvFpsCalc(buffer_len=10)

    # 座標履歴 #################################################################
    history_length = 16
    point_history = deque(maxlen=history_length)
    finger_gesture_history = deque(maxlen=history_length)
    wrist_history = deque(maxlen=8)
    mode = 0
    candidate_id = None
    candidate_count = 0
    last_fired_id = None
    cooldown_until = 0.0
    banner_text = ''
    banner_until = 0.0
    voice_engine = None
    if args.voice:
        try:
            import pyttsx3
            voice_engine = pyttsx3.init()
        except ImportError:
            print('Voice disabled: install pyttsx3 to use --voice.')
        except Exception as error:
            print(f'Voice disabled: could not initialize pyttsx3 ({error}).')

    while True:
        fps = cvFpsCalc.get()

        # キー処理(ESC：終了) #################################################
        key = cv.waitKey(10)
        if key == 27:  # ESC
            break
        number, mode = select_mode(key, mode)

        # カメラキャプチャ #####################################################
        ret, image = cap.read()
        if not ret:
            break
        image = cv.flip(image, 1)  # ミラー表示
        debug_image = copy.deepcopy(image)

        # 検出実施 #############################################################
        image = cv.cvtColor(image, cv.COLOR_BGR2RGB)

        image.flags.writeable = False
        mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=image)
        if use_static_image_mode:
            results = hands.detect(mp_image)
        else:
            results = hands.detect_for_video(mp_image, int(cv.getTickCount() /
                                                          cv.getTickFrequency() * 1000))
        image.flags.writeable = True

        #  ####################################################################
        if results.hand_landmarks:
            for hand_landmarks, handedness in zip(results.hand_landmarks,
                                                  results.handedness):
                # 外接矩形の計算
                brect = calc_bounding_rect(debug_image, hand_landmarks)
                # ランドマークの計算
                landmark_list = calc_landmark_list(debug_image, hand_landmarks)
                wrist_history.append(landmark_list[0])
                command_id = classify_command(landmark_list, wrist_history)
                command_text = COMMAND_LABELS[command_id]

                if candidate_id == command_id:
                    candidate_count += 1
                else:
                    candidate_id = command_id
                    candidate_count = 1

                now = time.monotonic()
                if (candidate_count >= stable_frames_required
                        and now >= cooldown_until
                        and command_id != last_fired_id):
                    banner_text = command_text
                    banner_until = now + 2.0
                    cooldown_until = now + args.cooldown
                    last_fired_id = command_id
                    if voice_engine is not None:
                        voice_engine.say(COMMAND_LABELS[command_id].split(' ', 1)[1])
                        voice_engine.runAndWait()

                # 相対座標・正規化座標への変換
                pre_processed_landmark_list = pre_process_landmark(
                    landmark_list)
                pre_processed_point_history_list = pre_process_point_history(
                    debug_image, point_history)
                # 学習データ保存
                logging_csv(number, mode, pre_processed_landmark_list,
                            pre_processed_point_history_list)

                # ハンドサイン分類
                hand_sign_id = keypoint_classifier(pre_processed_landmark_list)
                if hand_sign_id == 2:  # 指差しサイン
                    point_history.append(landmark_list[8])  # 人差指座標
                else:
                    point_history.append([0, 0])

                # フィンガージェスチャー分類
                finger_gesture_id = 0
                point_history_len = len(pre_processed_point_history_list)
                if point_history_len == (history_length * 2):
                    finger_gesture_id = point_history_classifier(
                        pre_processed_point_history_list)

                # 直近検出の中で最多のジェスチャーIDを算出
                finger_gesture_history.append(finger_gesture_id)
                most_common_fg_id = Counter(
                    finger_gesture_history).most_common()

                # 描画
                debug_image = draw_bounding_rect(use_brect, debug_image, brect)
                debug_image = draw_landmarks(debug_image, landmark_list)
                debug_image = draw_info_text(
                    debug_image,
                    brect,
                    handedness,
                    command_text,
                    point_history_classifier_labels[most_common_fg_id[0][0]],
                )
        else:
            point_history.append([0, 0])
            wrist_history.append([0, 0])
            candidate_id = None
            candidate_count = 0

        debug_image = draw_point_history(debug_image, point_history)
        debug_image = draw_info(debug_image, fps, mode, number)
        if time.monotonic() < banner_until:
            draw_command_banner(debug_image, banner_text)

        # 画面反映 #############################################################
        cv.imshow('Hand Gesture Recognition', debug_image)

    cap.release()
    cv.destroyAllWindows()


def select_mode(key, mode):
    number = -1
    if 48 <= key <= 57:  # 0 ~ 9
        number = key - 48
    if key == 110:  # n
        mode = 0
    if key == 107:  # k
        mode = 1
    if key == 104:  # h
        mode = 2
    return number, mode


def classify_command(landmark_list, wrist_history):
    thumb_up = (landmark_list[4][1] < landmark_list[3][1]
                < landmark_list[2][1] < landmark_list[1][1])
    thumb_down = (landmark_list[4][1] > landmark_list[3][1]
                  > landmark_list[2][1] > landmark_list[1][1])
    fingers_up = [
        landmark_list[8][1] < landmark_list[6][1],
        landmark_list[12][1] < landmark_list[10][1],
        landmark_list[16][1] < landmark_list[14][1],
        landmark_list[20][1] < landmark_list[18][1],
    ]
    index_up, middle_up, ring_up, pinky_up = fingers_up

    if thumb_up and not any(fingers_up):
        return 0
    if thumb_down and not any(fingers_up):
        return 1
    if all(fingers_up):
        if is_wave(wrist_history):
            return 3
        return 2
    if index_up and middle_up and not ring_up and not pinky_up:
        return 7
    if thumb_up and index_up and pinky_up and not middle_up and not ring_up:
        return 6
    if index_up and not middle_up and not ring_up and not pinky_up:
        return 5
    if not any(fingers_up) and not thumb_up and not thumb_down:
        return 4
    return 2


def is_wave(wrist_history):
    valid_points = [point for point in wrist_history if point != [0, 0]]
    if len(valid_points) < 4:
        return False
    horizontal_range = max(point[0] for point in valid_points) - min(
        point[0] for point in valid_points)
    return horizontal_range > 40


def calc_bounding_rect(image, landmarks):
    image_width, image_height = image.shape[1], image.shape[0]

    landmark_array = np.empty((0, 2), int)

    for _, landmark in enumerate(landmarks):
        landmark_x = min(int(landmark.x * image_width), image_width - 1)
        landmark_y = min(int(landmark.y * image_height), image_height - 1)

        landmark_point = [np.array((landmark_x, landmark_y))]

        landmark_array = np.append(landmark_array, landmark_point, axis=0)

    x, y, w, h = cv.boundingRect(landmark_array)

    return [x, y, x + w, y + h]


def calc_landmark_list(image, landmarks):
    image_width, image_height = image.shape[1], image.shape[0]

    landmark_point = []

    # キーポイント
    for _, landmark in enumerate(landmarks):
        landmark_x = min(int(landmark.x * image_width), image_width - 1)
        landmark_y = min(int(landmark.y * image_height), image_height - 1)
        # landmark_z = landmark.z

        landmark_point.append([landmark_x, landmark_y])

    return landmark_point


def pre_process_landmark(landmark_list):
    temp_landmark_list = copy.deepcopy(landmark_list)

    # 相対座標に変換
    base_x, base_y = 0, 0
    for index, landmark_point in enumerate(temp_landmark_list):
        if index == 0:
            base_x, base_y = landmark_point[0], landmark_point[1]

        temp_landmark_list[index][0] = temp_landmark_list[index][0] - base_x
        temp_landmark_list[index][1] = temp_landmark_list[index][1] - base_y

    # 1次元リストに変換
    temp_landmark_list = list(
        itertools.chain.from_iterable(temp_landmark_list))

    # 正規化
    max_value = max(list(map(abs, temp_landmark_list)))

    def normalize_(n):
        return n / max_value

    temp_landmark_list = list(map(normalize_, temp_landmark_list))

    return temp_landmark_list


def pre_process_point_history(image, point_history):
    image_width, image_height = image.shape[1], image.shape[0]

    temp_point_history = copy.deepcopy(point_history)

    # 相対座標に変換
    base_x, base_y = 0, 0
    for index, point in enumerate(temp_point_history):
        if index == 0:
            base_x, base_y = point[0], point[1]

        temp_point_history[index][0] = (temp_point_history[index][0] -
                                        base_x) / image_width
        temp_point_history[index][1] = (temp_point_history[index][1] -
                                        base_y) / image_height

    # 1次元リストに変換
    temp_point_history = list(
        itertools.chain.from_iterable(temp_point_history))

    return temp_point_history


def logging_csv(number, mode, landmark_list, point_history_list):
    if mode == 0:
        pass
    if mode == 1 and (0 <= number <= 9):
        csv_path = 'model/keypoint_classifier/keypoint.csv'
        with open(csv_path, 'a', newline="") as f:
            writer = csv.writer(f)
            writer.writerow([number, *landmark_list])
    if mode == 2 and (0 <= number <= 9):
        csv_path = 'model/point_history_classifier/point_history.csv'
        with open(csv_path, 'a', newline="") as f:
            writer = csv.writer(f)
            writer.writerow([number, *point_history_list])
    return


